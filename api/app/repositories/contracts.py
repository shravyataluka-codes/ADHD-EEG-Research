"""Storage-independent asynchronous repository contracts."""

from typing import Any, Protocol, TypeVar, runtime_checkable

from api.app.domain.entities import Analysis, Explanation, Recording, User

T = TypeVar("T")


class CrudRepository(Protocol[T]):
    async def create(self, entity: T) -> T: ...
    async def get(self, entity_id: str) -> T | None: ...
    async def update(self, entity_id: str, changes: dict[str, Any]) -> T | None: ...
    async def delete(self, entity_id: str) -> bool: ...


class UserRepository(CrudRepository[User], Protocol):
    async def get_by_email(self, email: str) -> User | None: ...
    async def get_by_firebase_uid(self, firebase_uid: str) -> User | None: ...


@runtime_checkable
class RecordingRepository(CrudRepository[Recording], Protocol):
    async def get_owned(self, recording_id: str, owner_id: str) -> Recording | None: ...
    async def list_owned(self, owner_id: str, *, limit: int = 100, skip: int = 0) -> list[Recording]: ...


class AnalysisRepository(CrudRepository[Analysis], Protocol):
    async def get_owned(self, analysis_id: str, owner_id: str) -> Analysis | None: ...
    async def list_owned(self, owner_id: str, *, limit: int = 100, skip: int = 0) -> list[Analysis]: ...
    async def list_for_recording(self, recording_id: str, owner_id: str, *, limit: int = 100, skip: int = 0) -> list[Analysis]: ...


class ExplanationRepository(CrudRepository[Explanation], Protocol):
    async def get_owned(self, explanation_id: str, owner_id: str) -> Explanation | None: ...
    async def list_owned(self, owner_id: str, *, limit: int = 100, skip: int = 0) -> list[Explanation]: ...
    async def list_for_analysis(self, analysis_id: str, owner_id: str, *, limit: int = 100, skip: int = 0) -> list[Explanation]: ...
