"""Provider independent file storage contract."""
from pathlib import Path
from typing import BinaryIO, Protocol, runtime_checkable


@runtime_checkable
class FileStorageProvider(Protocol):
    def save(self, key: str, source: BinaryIO, *, max_bytes: int) -> int: ...
    def retrieve(self, key: str) -> BinaryIO: ...
    def delete(self, key: str) -> bool: ...
    def exists(self, key: str) -> bool: ...
    def reference(self, key: str) -> str: ...


class StorageError(RuntimeError): ...
class InvalidStorageKey(StorageError): ...
class StorageConflict(StorageError): ...
class StorageUnavailable(StorageError): ...
